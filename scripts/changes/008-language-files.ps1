param(
 [string]$LocaleDirectory,
 [string]$OutputPath
)
$ErrorActionPreference='Stop'
$root=Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$enc=New-Object System.Text.UTF8Encoding($false)
if(!$LocaleDirectory){$LocaleDirectory=Join-Path $root 'frontend/src/i18n/locales'}
if(!$OutputPath){$OutputPath=Join-Path $root 'frontend/src/i18n/catalogs.generated.ts'}
$definitions=[ordered]@{}
foreach($file in (Get-ChildItem -LiteralPath $LocaleDirectory -Filter '*.json' -File|Sort-Object Name)){
 try{$locale=[IO.File]::ReadAllText($file.FullName,$enc)|ConvertFrom-Json}catch{throw "Invalid JSON in $($file.Name): $($_.Exception.Message)"}
 if($locale.enabled -isnot [bool]){throw "$($file.Name): enabled must be true or false"}
 if(!$locale.enabled){continue}
 $code=$locale.code
 if($code -isnot [string] -or $code -cnotmatch '^[a-z]{2,3}(-[A-Z]{2})?$' -or $file.BaseName -cne $code){throw "$($file.Name): use a language code matching the filename, e.g. fr.json with code fr"}
 if($definitions.Contains($code)){throw "Duplicate language code: $code"}
 if($locale.name -isnot [string] -or !$locale.name.Trim() -or $locale.documentTitle -isnot [string] -or !$locale.documentTitle.Trim()){throw "$($file.Name): name and documentTitle must be non-empty text"}
 if($null -eq $locale.messages -or $locale.messages -isnot [System.Management.Automation.PSCustomObject]){throw "$($file.Name): messages must be a JSON object"}
 $definitions[$code]=[ordered]@{name=$locale.name;documentTitle=$locale.documentTitle;messages=$locale.messages}
}
if(!$definitions.Contains('en') -or !$definitions.Contains('ny')){throw 'English (en) and default Chichewa (ny) must remain enabled'}
$source=$definitions['en'].messages
foreach($entry in $source.PSObject.Properties){if($entry.Value -isnot [string] -or $entry.Name -cne $entry.Value){throw "en.json must map every English source key to itself: $($entry.Name)"}}
foreach($code in $definitions.Keys){
 foreach($entry in $definitions[$code].messages.PSObject.Properties){
  $key=$entry.Name
  if(!($source.PSObject.Properties.Name -ccontains $key)){throw "${code}: unknown message key: $key"}
  if($entry.Value -isnot [string]){throw "${code}: translation must be text: $key"}
  if(!$entry.Value.Trim()){continue}
  $expected=@([regex]::Matches($key,'\{\d+\}')|ForEach-Object{$_.Value}|Sort-Object)
  $actual=@([regex]::Matches($entry.Value,'\{\d+\}')|ForEach-Object{$_.Value}|Sort-Object)
  if(($expected -join '|') -cne ($actual -join '|')){throw "${code}: preserve placeholders such as {0}: $key"}
 }
}
$content="// Generated by scripts/changes/008-language-files.ps1. Edit locales/*.json instead.`r`nexport const definitions = "+($definitions|ConvertTo-Json -Depth 8)+" as const;`r`n"
if(Test-Path -LiteralPath $OutputPath){
 $prior=[IO.File]::ReadAllText($OutputPath,$enc)
 if(!$prior.StartsWith('// Generated by scripts/changes/008-language-files.ps1.')){throw "Refusing to replace an unrecognized generated file: $OutputPath"}
 if($prior -ceq $content){Write-Output "Validated $($definitions.Count) language files (unchanged).";exit 0}
}
[IO.File]::WriteAllText("$OutputPath.tmp",$content,$enc)
Move-Item -LiteralPath "$OutputPath.tmp" -Destination $OutputPath -Force
Write-Output "Generated $($definitions.Count) languages from editable JSON files."